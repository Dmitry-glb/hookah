'use strict';
const test = require('node:test'), assert = require('node:assert/strict'), fs = require('node:fs'), path = require('node:path'), http = require('node:http');
const skip = process.env.E2E !== '1';
test('e2e: quick 7-minute timer, durable pause, short recording, cloud outbox and private history', { skip, timeout: 60000 }, async () => {
    const root = path.resolve(__dirname, '..');
    const server = http.createServer((req, res) => {
        const file = path.resolve(root, '.' + (new URL(req.url, 'http://local').pathname === '/' ? '/index.html' : new URL(req.url, 'http://local').pathname));
        const type = { '.html': 'text/html; charset=utf-8', '.js': 'text/javascript', '.css': 'text/css', '.json': 'application/json', '.png': 'image/png', '.ttf': 'font/ttf', '.svg': 'image/svg+xml' };
        fs.readFile(file, (error, data) => { res.writeHead(error ? 404 : 200, { 'Content-Type': type[path.extname(file)] || 'application/octet-stream' }); res.end(error ? '' : data); });
    });
    await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
    const { chromium } = require('playwright');
    const browser = await chromium.launch({ headless: true, executablePath: process.env.CHROME_PATH || (fs.existsSync('C:/Program Files/Google/Chrome/Application/chrome.exe') ? 'C:/Program Files/Google/Chrome/Application/chrome.exe' : undefined) });
    try {
        const { default: worker, PreheatCoordinator } = await import('../worker/index.mjs');
        const data = new Map(); let alarm;
        data.set('timer', { state: null, revision: 2, updatedAt: Date.now() });
        const storage = { async get(key) { return structuredClone(data.get(key)); }, async put(key, value) { if (typeof key === 'object') for (const [k, v] of Object.entries(key)) data.set(k, structuredClone(v)); else data.set(key, structuredClone(value)); }, async delete(keys) { for (const key of Array.isArray(keys) ? keys : [keys]) data.delete(key); }, async list({ prefix }) { return new Map([...data].filter(([key]) => key.startsWith(prefix))); }, async setAlarm(at) { alarm = at; }, async deleteAlarm() { alarm = null; } };
        const origin = `http://127.0.0.1:${server.address().port}`;
        const env = { PREHEAT_TOKEN: 'browser-test-private-key', ALLOWED_ORIGIN: origin };
        const coordinator = new PreheatCoordinator({ storage, blockConcurrencyWhile: fn => fn() }, env);
        env.PREHEAT_COORDINATOR = { idFromName: () => 'one', get: () => coordinator };
        const context = await browser.newContext({ viewport: { width: 390, height: 844 }, reducedMotion: 'reduce' });
        const page = await context.newPage(); const errors = [];
        page.on('pageerror', error => errors.push(error.message));
        let offline = false;
        await page.route('https://cloud.test/**', async route => {
            if (offline) return route.abort();
            const request = route.request();
            const response = await worker.fetch(new Request(request.url(), { method: request.method(), headers: request.headers(), ...(request.postData() ? { body: request.postData() } : {}) }), env);
            await route.fulfill({ status: response.status, headers: Object.fromEntries(response.headers), body: await response.text() });
        });
        await page.goto(origin);
        await page.waitForFunction(() => window.DimHookahUI?.getState().ready);
        assert.equal(await page.isVisible('#quick-preheat'), true);
        assert.equal(await page.isVisible('#setup-form'), false);
        await page.click('#quick-preheat');
        await page.waitForSelector('#panel-timer:not([hidden])');
        let timer = await page.evaluate(() => JSON.parse(localStorage.getItem('hookah_active_session')));
        assert.equal(timer.targetTimestamp - timer.stepStartTime, 420000);
        await page.click('#pause-session');
        const paused = await page.textContent('#timer');
        await page.waitForTimeout(1100);
        assert.equal(await page.textContent('#timer'), paused);
        await page.reload();
        await page.waitForSelector('#panel-timer:not([hidden])');
        assert.equal(await page.textContent('#timer'), paused);
        assert.ok(await page.evaluate(() => timerPausedAt));
        await page.click('#pause-session');
        assert.equal(await page.evaluate(() => timerPausedAt), null);
        await page.evaluate(() => DimHookahUI.showTab('catalog'));
        await page.evaluate(() => document.dispatchEvent(new Event('visibilitychange')));
        assert.equal(await page.isVisible('#panel-timer'), true);

        await page.evaluate(() => DimHookahUI.showTab('settings'));
        await page.fill('#cloud-url', 'https://cloud.test');
        await page.fill('#cloud-token', 'browser-test-private-key');
        await page.check('#cloud-history');
        await page.click('#cloud-connect');
        await page.waitForFunction(() => document.getElementById('cloud-status').textContent.startsWith('Подключено'));
        await page.waitForFunction(() => !JSON.parse(localStorage.getItem('hookah_cloud_queue_v1')).timer);
        assert.equal(data.get('timer').state.stage, 'warmup');
        assert.ok(alarm > Date.now());
        offline = true;
        await page.evaluate(() => toggleSessionPause());
        await page.waitForFunction(() => JSON.parse(localStorage.getItem('hookah_cloud_queue_v1')).timer?.state.pausedAt);
        await page.reload();
        await page.waitForSelector('#panel-timer:not([hidden])');
        assert.ok(await page.evaluate(() => timerPausedAt));
        offline = false;
        await page.evaluate(() => window.dispatchEvent(new Event('online')));
        await page.waitForFunction(() => !JSON.parse(localStorage.getItem('hookah_cloud_queue_v1')).timer);
        assert.ok(data.get('timer').state.pausedAt);
        assert.equal(alarm, null);

        await page.evaluate(() => { savedBowls = ['Моя чаша']; populateSelects(); openManualAddModal(); });
        assert.equal(await page.locator('.optional-fields').evaluate(node => node.open), false);
        assert.equal(await page.isVisible('#manual-duration-input'), false);
        await page.selectOption('#manual-rating-select', '4.5');
        await page.click('button[onclick="saveManualSession()"]');
        await page.waitForSelector('#manual-add-modal.hidden', { state: 'attached' });
        await page.waitForFunction(() => JSON.parse(localStorage.getItem('hookah_sessions')).length === 1);
        await page.waitForFunction(() => JSON.parse(localStorage.getItem('hookah_cloud_queue_v1')).history.length === 0);
        const sessions = await page.evaluate(() => JSON.parse(localStorage.getItem('hookah_sessions')));
        assert.equal(sessions[0].smokeDuration, 0, 'omitted duration must not become a fictional hour');
        assert.equal(sessions[0].actualWarmupDuration, 0);
        assert.equal(sessions[0].rating, 4.5);
        assert.equal(data.get('history').length, 1);
        assert.equal(data.get('history')[0].session.id, sessions[0].id);
        await page.evaluate(() => DimHookahUI.showTab('settings'));
        await page.click('#cloud-disconnect');
        await page.waitForFunction(() => localStorage.getItem('hookah_cloud_v1') === null);
        assert.equal(await page.evaluate(() => localStorage.getItem('hookah_cloud_v1')), null);
        assert.equal(await page.evaluate(() => JSON.parse(localStorage.getItem('hookah_active_session')).stage), 'warmup');
        assert.equal(await page.evaluate(() => JSON.parse(localStorage.getItem('hookah_sessions')).length), 1);
        await page.evaluate(() => renderData([{ id: 12, date: '05.11.2026', bowl: '<img src=x onerror="window.untrustedRan=true">', comment: '<img src=x onerror="window.untrustedRan=true">', rating: 4, mix: [{ brand: 'Test', flavor: '<img src=x onerror="window.untrustedRan=true">', weight: 0 }] }]));
        assert.equal(await page.locator('#history-list img').count(), 0);
        assert.equal(await page.evaluate(() => Boolean(window.untrustedRan)), false);
        assert.deepEqual(errors, []);

        // New PWA controls persist selection, and the restored reel actually moves.
        const reelPage = await browser.newPage({ viewport: { width: 390, height: 844 }, reducedMotion: 'no-preference' });
        reelPage.on('pageerror', error => errors.push(error.message));
        await reelPage.goto(origin);
        await reelPage.waitForFunction(() => window.DimHookahUI?.getState().ready);
        assert.equal(await reelPage.locator('.comic-hero, .roulette-intro').count(), 0);
        assert.equal(await reelPage.locator('#quick-preheat b').textContent(), '07:00');
        assert.equal(await reelPage.locator('#warmup-slider').getAttribute('min'), '4');
        assert.equal(await reelPage.locator('#warmup-slider').getAttribute('max'), '10');
        await reelPage.waitForFunction(() => document.querySelector('.quick-flame img').naturalWidth > 0);
        await reelPage.evaluate(() => setWarmupPreset(1));
        assert.equal(await reelPage.locator('#quick-preheat b').textContent(), '04:00');
        assert.equal(await reelPage.locator('#warmup-minus').isDisabled(), true);
        await reelPage.evaluate(() => setWarmupPreset(59));
        assert.equal(await reelPage.locator('#quick-preheat b').textContent(), '10:00');
        assert.equal(await reelPage.locator('#warmup-plus').isDisabled(), true);
        // Existing out-of-range preferences migrate without touching saved sessions.
        await reelPage.evaluate(() => localStorage.setItem('hookah_warmup_minutes_v1', '15'));
        await reelPage.reload();
        await reelPage.waitForFunction(() => window.DimHookahUI?.getState().ready);
        assert.equal(await reelPage.locator('#quick-preheat b').textContent(), '10:00');
        await reelPage.click('[data-warmup-choice="5"]');
        assert.equal(await reelPage.locator('#quick-preheat b').textContent(), '05:00');
        await reelPage.locator('#warmup-slider').evaluate(input => { input.value = '10'; input.dispatchEvent(new Event('input', { bubbles: true })); });
        assert.equal(await reelPage.locator('#warmup-picker-value').textContent(), '10 мин');
        await reelPage.click('[data-warmup-choice="5"]');
        await reelPage.reload();
        await reelPage.waitForFunction(() => window.DimHookahUI?.getState().ready);
        assert.equal(await reelPage.locator('#quick-preheat b').textContent(), '05:00');
        await reelPage.click('#quick-preheat');
        const fiveMinuteState = await reelPage.evaluate(() => JSON.parse(localStorage.getItem('hookah_active_session')));
        assert.equal(fiveMinuteState.targetTimestamp - fiveMinuteState.stepStartTime, 300000);
        await reelPage.click('.timer-toolbar button:last-child');
        await reelPage.click('#confirm-ok-btn');
        await reelPage.reload();
        await reelPage.waitForFunction(() => window.DimHookahUI?.getState().ready);
        assert.equal(await reelPage.locator('#quick-preheat b').textContent(), '05:00');
        await reelPage.click('#tab-roulette');
        assert.equal(await reelPage.locator('#roulette-window').isVisible(), true);
        assert.equal(await reelPage.locator('#roulette-fast').isChecked(), false);
        const startedAt = Date.now();
        await reelPage.click('#roulette-spin');
        await reelPage.waitForTimeout(200);
        const firstTransform = await reelPage.locator('#roulette-track').evaluate(node => getComputedStyle(node).transform);
        await reelPage.waitForTimeout(250);
        const secondTransform = await reelPage.locator('#roulette-track').evaluate(node => getComputedStyle(node).transform);
        assert.notEqual(firstTransform, secondTransform, 'reel cards must visibly travel, not just delay the result');
        await reelPage.waitForSelector('#roulette-result.is-visible', { timeout: 9000 });
        assert.ok(Date.now() - startedAt >= 4500);
        const centerError = await reelPage.evaluate(() => {
            const card = document.querySelector('.reel-card.is-winner').getBoundingClientRect();
            const frame = document.getElementById('roulette-window').getBoundingClientRect();
            return Math.abs(card.left + card.width / 2 - frame.left - frame.width / 2);
        });
        assert.ok(centerError < 3, `winner must align with the pointer, error ${centerError}px`);
        for (const width of [320, 390, 768, 1280]) {
            await reelPage.setViewportSize({ width, height: 844 });
            for (const tab of ['home', 'roulette', 'catalog', 'history']) {
                await reelPage.evaluate(tab => DimHookahUI.showTab(tab), tab);
                assert.equal(await reelPage.evaluate(() => document.documentElement.scrollWidth > innerWidth + 1), false);
                const heading = reelPage.locator(`#panel-${tab} > .section-head`);
                if (await heading.count()) assert.ok((await heading.boundingBox()).height < 60, `${tab}: heading wastes vertical space`);
            }
        }
        assert.deepEqual(errors, []);
    } finally { await browser.close(); await new Promise(resolve => server.close(resolve)); }
});
